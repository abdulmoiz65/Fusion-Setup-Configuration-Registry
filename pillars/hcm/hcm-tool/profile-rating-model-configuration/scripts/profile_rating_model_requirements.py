def _type_matches(value, expected):
    if expected == "object":
        return isinstance(value, dict)
    if expected == "array":
        return isinstance(value, list)
    if expected == "string":
        return isinstance(value, str)
    if expected == "integer":
        return isinstance(value, int) and not isinstance(value, bool)
    if expected == "number":
        return isinstance(value, (int, float)) and not isinstance(value, bool)
    if expected == "boolean":
        return isinstance(value, bool)
    if expected == "null":
        return value is None
    return True


def _schema_violations(value, schema, path=""):
    """Validate the JSON-Schema features used by the bundled requirements contract."""
    violations = []
    expected = schema.get("type")
    if expected:
        expected_types = expected if isinstance(expected, list) else [expected]
        if not any(_type_matches(value, item) for item in expected_types):
            violations.append((path or "$", "Expected type %s." % ", ".join(expected_types)))
            return violations
    if "const" in schema and value != schema["const"]:
        violations.append((path or "$", "Value must equal %r." % schema["const"]))
    if "enum" in schema and value not in schema["enum"]:
        violations.append((path or "$", "Value is not one of the supported values."))
    if isinstance(value, str):
        if len(value) < schema.get("minLength", 0):
            violations.append((path or "$", "String is shorter than the required minimum."))
        pattern = schema.get("pattern")
        if pattern and not re.match(pattern, value):
            violations.append((path or "$", "String does not match the required pattern."))
        if schema.get("format") == "date":
            try:
                parsed = datetime.strptime(value, "%Y-%m-%d")
                if parsed.strftime("%Y-%m-%d") != value:
                    raise ValueError("noncanonical date")
            except ValueError:
                violations.append((path or "$", "Date must use a valid YYYY-MM-DD value."))
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        if "minimum" in schema and value < schema["minimum"]:
            violations.append((path or "$", "Number is below the allowed minimum."))
        if "maximum" in schema and value > schema["maximum"]:
            violations.append((path or "$", "Number exceeds the allowed maximum."))
    if isinstance(value, list):
        if len(value) < schema.get("minItems", 0):
            violations.append((path or "$", "Array has fewer than the required number of items."))
        if schema.get("uniqueItems"):
            serialized = [json.dumps(item, sort_keys=True) for item in value]
            if len(serialized) != len(set(serialized)):
                violations.append((path or "$", "Array items must be unique."))
        item_schema = schema.get("items")
        if item_schema:
            for index, item in enumerate(value):
                item_path = "%s[%d]" % (path, index) if path else "[%d]" % index
                violations.extend(_schema_violations(item, item_schema, item_path))
    if isinstance(value, dict):
        properties = schema.get("properties", {})
        for required in schema.get("required", []):
            if required not in value:
                field = "%s.%s" % (path, required) if path else required
                violations.append((field, "Required property is missing."))
        for key, item in value.items():
            field = "%s.%s" % (path, key) if path else key
            if key in properties:
                violations.extend(_schema_violations(item, properties[key], field))
            elif schema.get("additionalProperties") is False:
                violations.append((field, "Additional property is not allowed."))
    return violations


def _requirements_schema():
    with open(SCHEMA_PATH, "r", encoding="utf-8") as stream:
        return json.load(stream)


def _get(data, path, default=""):
    value = data
    for part in path.split("."):
        if not isinstance(value, dict):
            return default
        value = value.get(part, default)
    return value


def _put(data, path, value):
    parts = path.split(".")
    target = data
    for part in parts[:-1]:
        target = target.setdefault(part, {})
    target[parts[-1]] = value


def _scalar(value):
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (list, tuple)):
        return "; ".join(str(item) for item in value)
    return str(value)


def _coerce(value):
    text = str(value).strip()
    if text.lower() in ("true", "yes", "y"):
        return True
    if text.lower() in ("false", "no", "n"):
        return False
    if text == "":
        return None
    if re.match(r"^-?[0-9]+$", text):
        return int(text)
    if re.match(r"^-?[0-9]+\.[0-9]+$", text):
        return float(text)
    return text


def _column(index):
    value = ""
    while index:
        index, remainder = divmod(index - 1, 26)
        value = chr(65 + remainder) + value
    return value


def _sheet_xml(rows):
    output = ['<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
              '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>']
    for row_number, row in enumerate(rows, 1):
        output.append('<row r="%d">' % row_number)
        for column_number, raw in enumerate(row, 1):
            value = _scalar(raw)
            if value == "":
                continue
            reference = "%s%d" % (_column(column_number), row_number)
            output.append('<c r="%s" t="inlineStr"><is><t xml:space="preserve">%s</t></is></c>' %
                          (reference, escape(value)))
        output.append("</row>")
    output.append("</sheetData></worksheet>")
    return "".join(output).encode("utf-8")


def write_xlsx(path, sheets):
    names = list(sheets.keys())
    content_types = ['<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
                     '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">',
                     '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>',
                     '<Default Extension="xml" ContentType="application/xml"/>',
                     '<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>']
    for index in range(1, len(names) + 1):
        content_types.append('<Override PartName="/xl/worksheets/sheet%d.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>' % index)
    content_types.append("</Types>")
    package_rels = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
                    '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
                    '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>'
                    '</Relationships>')
    workbook = ['<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
                '<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets>']
    rels = ['<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">']
    for index, name in enumerate(names, 1):
        workbook.append('<sheet name="%s" sheetId="%d" r:id="rId%d"/>' % (escape(name), index, index))
        rels.append('<Relationship Id="rId%d" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet%d.xml"/>' % (index, index))
    workbook.append("</sheets></workbook>")
    rels.append("</Relationships>")
    parent = os.path.dirname(os.path.abspath(path))
    if parent and not os.path.isdir(parent):
        os.makedirs(parent)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("[Content_Types].xml", "".join(content_types))
        archive.writestr("_rels/.rels", package_rels)
        archive.writestr("xl/workbook.xml", "".join(workbook))
        archive.writestr("xl/_rels/workbook.xml.rels", "".join(rels))
        for index, name in enumerate(names, 1):
            archive.writestr("xl/worksheets/sheet%d.xml" % index, _sheet_xml(sheets[name]))


def read_xlsx(path):
    ns = {"x": "http://schemas.openxmlformats.org/spreadsheetml/2006/main",
          "r": "http://schemas.openxmlformats.org/officeDocument/2006/relationships",
          "p": "http://schemas.openxmlformats.org/package/2006/relationships"}
    result = {}
    with zipfile.ZipFile(path) as archive:
        shared = []
        if "xl/sharedStrings.xml" in archive.namelist():
            root = ET.fromstring(archive.read("xl/sharedStrings.xml"))
            for item in root.findall("x:si", ns):
                shared.append("".join(node.text or "" for node in item.findall(".//x:t", ns)))
        workbook = ET.fromstring(archive.read("xl/workbook.xml"))
        relations = ET.fromstring(archive.read("xl/_rels/workbook.xml.rels"))
        targets = {node.attrib["Id"]: node.attrib["Target"] for node in relations.findall("p:Relationship", ns)}
        for sheet in workbook.findall("x:sheets/x:sheet", ns):
            name = sheet.attrib["name"]
            relation = sheet.attrib["{%s}id" % ns["r"]]
            target = targets[relation]
            member = "xl/" + target.lstrip("/")
            root = ET.fromstring(archive.read(member))
            rows = []
            for row in root.findall("x:sheetData/x:row", ns):
                cells = {}
                max_col = 0
                for cell in row.findall("x:c", ns):
                    reference = cell.attrib.get("r", "A1")
                    letters = re.match(r"[A-Z]+", reference).group(0)
                    column = 0
                    for letter in letters:
                        column = column * 26 + ord(letter) - 64
                    max_col = max(max_col, column)
                    kind = cell.attrib.get("t")
                    if kind == "inlineStr":
                        value = "".join(node.text or "" for node in cell.findall(".//x:t", ns))
                    else:
                        node = cell.find("x:v", ns)
                        value = "" if node is None else (node.text or "")
                        if kind == "s" and value:
                            value = shared[int(value)]
                    cells[column] = value
                rows.append([cells.get(index, "") for index in range(1, max_col + 1)])
            result[name] = rows
    return result


def workbook_sheets(data):
    consumers = _get(data, "model.consumers", []) or []
    levels = data.get("levels", [])
    calculated = bool(_get(data, "performance.calculated_rating", False))
    review = calculated or any(level.get("review_point") is not None or level.get("range_from") is not None for level in levels)
    categories = bool(_get(data, "talent_review.categories_required", False)) or any(level.get("category") for level in levels)
    distributions = bool(_get(data, "compensation.direct_distributions_required", False)) or bool(_get(data, "performance.target_distribution", []))
    sheets = {}
    sheets["Instructions"] = [
        ["Profile Rating Model Requirements", "Version 1.0"],
        ["Rule", "One create-or-reuse model; do not update, delete, or configure downstream consumers."],
        ["Selected consumers", _scalar(consumers)],
        ["Resubmission", "Retain this source and create a new project artifact version for material corrections."],
    ]
    sheets["Model Requirements"] = [["Field", "Value"]] + [[label, _scalar(_get(data, path, ""))] for label, path in MODEL_ROWS]
    sheets["Rating Scale"] = [list(LEVEL_FIELDS)] + [[_scalar(level.get(field, "")) for field in LEVEL_FIELDS] for level in levels]
    if review:
        sheets["Review Points and Ranges"] = [["level_code", "review_point", "range_from", "range_to"]] + [[level.get("code", ""), level.get("review_point", ""), level.get("range_from", ""), level.get("range_to", "")] for level in levels]
    if categories:
        sheets["Rating Categories"] = [["level_code", "category"]] + [[level.get("code", ""), level.get("category", "")] for level in levels]
    if distributions:
        rows = [["owner", "level_code", "minimum", "maximum_or_percentage", "threshold"]]
        if "Compensation" in consumers:
            threshold = _get(data, "compensation.distribution_threshold", "")
            rows += [["Compensation model", level.get("code", ""), level.get("distribution_min", ""), level.get("distribution_max", ""), threshold] for level in levels]
        for item in _get(data, "performance.target_distribution", []) or []:
            rows.append(["Performance downstream", item.get("level_code", ""), "", item.get("percentage", ""), ""])
        sheets["Rating Distributions"] = rows
    sheets["Translations"] = [["language", "entity_type", "entity_code", "name", "short_description", "full_description"]] + [[item.get(field, "") for field in ("language", "entity_type", "entity_code", "name", "short_description", "full_description")] for item in data.get("translations", [])]
    sheets["Consumer Handoffs"] = [list(HANDOFF_FIELDS)] + [[_scalar(item.get(field, "")) for field in HANDOFF_FIELDS] for item in data.get("handoffs", [])]
    return sheets


def template_workbook_sheets(consumers=(), level_count=5, source_name="profile-rating-model-intake-template.xlsx"):
    """Return a fillable intake workbook without requiring implementation-ready data."""
    selected_consumers = tuple(dict.fromkeys(str(item) for item in consumers if str(item)))
    unsupported = [item for item in selected_consumers if item not in CONSUMERS]
    if unsupported:
        raise ValueError("Unsupported consumer: %s" % unsupported[0])
    if level_count < 2:
        raise ValueError("Template level count must be at least 2.")

    initial_values = {
        "schema_version": "1.0",
        "operation": "create_or_reuse",
        "source.type": "generated_workbook",
        "source.name": source_name,
        "source.version": "1.0",
        "model.consumers": _scalar(selected_consumers),
    }
    selection = _scalar(selected_consumers) or "Not selected; complete model.consumers in the workbook"
    sheets = {
        "Instructions": [
            ["Profile Rating Model Fillable Template", "Version 1.0"],
            ["Purpose", "Capture one create-or-reuse Profile Rating Model before discovery, validation, or implementation."],
            ["Selected consumers", selection],
            ["How to complete", "Enter values in Model Requirements, complete every intended Rating Scale row, and fill only applicable conditional sheets."],
            ["Lists", "Separate multiple consumers and languages with semicolons."],
            ["Dates", "Use YYYY-MM-DD."],
            ["Conditional sheets", "Blank optional sheets do not assert a requirement. Complete them only when the selected business use needs them."],
            ["Examples", "Examples in Field Guidance are synthetic illustrations; replace them with your design."],
            ["Next step", "Return the completed workbook for validation. This template generation performs no Fusion read or write."],
        ],
        "Field Guidance": [
            ["Section", "Field or Columns", "Required When", "What to Enter", "Synthetic Example"]
        ] + [list(row) for row in TEMPLATE_FIELD_GUIDANCE],
        "Model Requirements": [["Field", "Value"]] + [
            [label, initial_values.get(path, "")] for label, path in MODEL_ROWS
        ],
        "Rating Scale": [list(LEVEL_FIELDS)] + [
            [sequence] + [""] * (len(LEVEL_FIELDS) - 1)
            for sequence in range(1, level_count + 1)
        ],
    }

    universal = not selected_consumers
    if universal or "Performance Management" in selected_consumers:
        sheets["Review Points and Ranges"] = [
            ["level_code", "review_point", "range_from", "range_to"]
        ]
    if universal or "Talent Review and Succession" in selected_consumers:
        sheets["Rating Categories"] = [["level_code", "category"]]
    if universal or any(
        item in selected_consumers for item in ("Performance Management", "Compensation")
    ):
        sheets["Rating Distributions"] = [
            ["owner", "level_code", "minimum", "maximum_or_percentage", "threshold"]
        ]
    sheets["Translations"] = [
        ["language", "entity_type", "entity_code", "name", "short_description", "full_description"]
    ]
    sheets["Consumer Handoffs"] = [list(HANDOFF_FIELDS)] + [
        [consumer] + [""] * (len(HANDOFF_FIELDS) - 1)
        for consumer in selected_consumers
    ]
    return sheets


def workbook_to_data(path):
    sheets = read_xlsx(path)
    data = WorkbookData({"source": {}, "model": {}, "levels": [], "handoffs": [], "translations": []})
    data.workbook_issues = []
    model_rows = sheets.get("Model Requirements", [])
    for row in model_rows[1:]:
        if len(row) < 2 or not row[0]:
            continue
        if row[0] in MODEL_ARRAY_PATHS:
            value = [item.strip() for item in str(row[1]).split(";") if item.strip()]
        elif row[0] in MODEL_COERCED_PATHS:
            value = _coerce(row[1])
        elif row[0] == "model.effective_end_date" and str(row[1]).strip() == "":
            value = None
        else:
            value = str(row[1]).strip()
        _put(data, row[0], value)
    rating = sheets.get("Rating Scale", [])
    if rating:
        headers = rating[0]
        for row in rating[1:]:
            if not any(row):
                continue
            item = {}
            for index, header in enumerate(headers):
                item[header] = _coerce(row[index] if index < len(row) else "")
            data["levels"].append(item)

    def find_level(code, sheet, row_number):
        matches = [level for level in data["levels"] if level.get("code") == code]
        if len(matches) != 1:
            data.workbook_issues.append({
                "field": "workbook.%s.level_code" % sheet.lower().replace(" ", "_"),
                "issue": "Level code %r does not identify exactly one Rating Scale row." % code,
                "sheet": sheet,
                "row": row_number,
                "impact": "Conditional values could be applied to the wrong rating level.",
                "correction": "Use one exact unique level_code from Rating Scale.",
            })
            return None
        return matches[0]

    review_rows = sheets.get("Review Points and Ranges", [])
    if review_rows:
        seen = set()
        for row_number, row in enumerate(review_rows[1:], 2):
            if not any(row):
                continue
            code = row[0] if row else ""
            if code in seen:
                data.workbook_issues.append({
                    "field": "workbook.review_points.level_code", "issue": "Duplicate review row for %r." % code,
                    "sheet": "Review Points and Ranges", "row": row_number,
                    "impact": "More than one review mapping exists for a rating level.",
                    "correction": "Keep one review row per level_code.",
                })
                continue
            seen.add(code)
            level = find_level(code, "Review Points and Ranges", row_number)
            if level is not None:
                for index, field in enumerate(("review_point", "range_from", "range_to"), 1):
                    level[field] = _coerce(row[index] if index < len(row) else "")

    category_rows = sheets.get("Rating Categories", [])
    if category_rows:
        seen = set()
        for row_number, row in enumerate(category_rows[1:], 2):
            if not any(row):
                continue
            code = row[0] if row else ""
            if code in seen:
                data.workbook_issues.append({
                    "field": "workbook.rating_categories.level_code", "issue": "Duplicate category row for %r." % code,
                    "sheet": "Rating Categories", "row": row_number,
                    "impact": "More than one category exists for a rating level.",
                    "correction": "Keep one category row per level_code.",
                })
                continue
            seen.add(code)
            level = find_level(code, "Rating Categories", row_number)
            if level is not None:
                level["category"] = _coerce(row[1] if len(row) > 1 else "")

    distribution_rows = sheets.get("Rating Distributions", [])
    if distribution_rows:
        performance_rows = []
        performance_codes = set()
        compensation_codes = set()
        thresholds = set()
        for row_number, row in enumerate(distribution_rows[1:], 2):
            if not any(row):
                continue
            owner = row[0] if row else ""
            code = row[1] if len(row) > 1 else ""
            level = find_level(code, "Rating Distributions", row_number)
            if level is None:
                continue
            if owner == "Compensation model":
                if code in compensation_codes:
                    data.workbook_issues.append({
                        "field": "workbook.rating_distributions.level_code", "issue": "Duplicate Compensation row for %r." % code,
                        "sheet": "Rating Distributions", "row": row_number,
                        "impact": "More than one direct distribution exists for a rating level.",
                        "correction": "Keep one Compensation model row per level_code.",
                    })
                    continue
                compensation_codes.add(code)
                level["distribution_min"] = _coerce(row[2] if len(row) > 2 else "")
                level["distribution_max"] = _coerce(row[3] if len(row) > 3 else "")
                threshold = _coerce(row[4] if len(row) > 4 else "")
                if threshold is not None:
                    thresholds.add(threshold)
            elif owner == "Performance downstream":
                if code in performance_codes:
                    data.workbook_issues.append({
                        "field": "workbook.performance_distribution.level_code", "issue": "Duplicate Performance row for %r." % code,
                        "sheet": "Rating Distributions", "row": row_number,
                        "impact": "More than one target percentage exists for a rating level.",
                        "correction": "Keep one Performance downstream row per level_code.",
                    })
                    continue
                performance_codes.add(code)
                performance_rows.append({"level_code": code, "percentage": _coerce(row[3] if len(row) > 3 else "")})
            else:
                data.workbook_issues.append({
                    "field": "workbook.rating_distributions.owner", "issue": "Unsupported distribution owner %r." % owner,
                    "sheet": "Rating Distributions", "row": row_number,
                    "impact": "The value could be assigned to the wrong product owner.",
                    "correction": "Use Compensation model or Performance downstream.",
                })
        if len(thresholds) > 1:
            data.workbook_issues.append({
                "field": "workbook.compensation.distribution_threshold", "issue": "Compensation rows contain conflicting thresholds.",
                "sheet": "Rating Distributions", "row": None,
                "impact": "The model would have no single distribution threshold.",
                "correction": "Use one threshold value on every Compensation model row.",
            })
        elif thresholds:
            data.setdefault("compensation", {})["distribution_threshold"] = next(iter(thresholds))
        if performance_codes:
            data.setdefault("performance", {})["target_distribution"] = performance_rows
    trans = sheets.get("Translations", [])
    if trans:
        for row in trans[1:]:
            if any(row):
                data["translations"].append({field: (row[index] if index < len(row) else "") for index, field in enumerate(trans[0])})
    handoffs = sheets.get("Consumer Handoffs", [])
    if handoffs:
        for row in handoffs[1:]:
            if any(row):
                item = {field: (row[index] if index < len(row) else "") for index, field in enumerate(handoffs[0])}
                for field in ("test_cases", "open_decisions"):
                    item[field] = [part.strip() for part in str(item.get(field, "")).split(";") if part.strip()]
                data["handoffs"].append(item)
    return data


def _issue(issues, field, issue, impact, correction, sheet="Model Requirements", row=None, severity="blocking"):
    cell = None
    if row is not None:
        cell = "%s%d" % ("B" if sheet == "Model Requirements" else "A", row)
    issues.append({"source": "normalized requirements", "worksheet": sheet, "row": row,
                   "field": field, "cell": cell, "issue": issue,
                   "business_impact": impact, "recommended_correction": correction,
                   "severity": severity})


def validate(data):
    issues = []
    for item in getattr(data, "workbook_issues", []):
        _issue(issues, item["field"], item["issue"], item["impact"], item["correction"], item["sheet"], item["row"])
    for field, message in _schema_violations(data, _requirements_schema()):
        sheet = "Model Requirements"
        row = None
        if field.startswith("levels"):
            sheet = "Rating Scale"
            match = re.match(r"levels\[([0-9]+)\]", field)
            row = int(match.group(1)) + 2 if match else None
        elif field.startswith("translations"):
            sheet = "Translations"
        elif field.startswith("handoffs"):
            sheet = "Consumer Handoffs"
        _issue(issues, field, "Schema contract: %s" % message,
               "The normalized request does not match the governed technical contract.",
               "Correct the value to satisfy profile-rating-model-requirements.schema.json.",
               sheet, row)
    if data.get("operation") != "create_or_reuse":
        _issue(issues, "operation", "Only create_or_reuse is supported.", "An update or delete could change a shared model.", "Set create_or_reuse or route the request outside V1.")
    for path in ("request_id", "source.type", "source.name", "source.version", "model.business_purpose", "model.intended_population", "model.code", "model.name", "model.description", "model.effective_start_date"):
        if _get(data, path, None) in (None, "", []):
            _issue(issues, path, "Required value is missing.", "The model cannot be traced or safely configured.", "Provide a specific value.")
    code = _get(data, "model.code", "")
    if code and not re.match(r"^[A-Z][A-Z0-9_]*$", str(code)):
        _issue(issues, "model.code", "Code must start with an uppercase letter and use uppercase letters, digits, or underscores.", "An unstable code impairs reuse and migration.", "Provide a stable uppercase code.")
    consumers = _get(data, "model.consumers", []) or []
    if not consumers:
        _issue(issues, "model.consumers", "At least one consumer is required.", "Applicable component rules cannot be determined.", "Select one or more supported consumers.")
    for consumer in consumers:
        if consumer not in CONSUMERS:
            _issue(issues, "model.consumers", "Unsupported consumer: %s." % consumer, "The skill has no governed handoff for it.", "Select a supported consumer.")
    levels = data.get("levels", [])
    if len(levels) < 2:
        _issue(issues, "levels", "At least two levels are required.", "The model has no usable scale.", "Provide two or more ordered levels.", "Rating Scale")
    sequences = [level.get("sequence") for level in levels]
    codes = [level.get("code") for level in levels]
    if len(sequences) != len(set(str(item) for item in sequences)) or sequences != list(range(1, len(levels) + 1)):
        _issue(issues, "levels.sequence", "Sequences must be unique and consecutive from 1.", "Level order is ambiguous.", "Renumber levels in intended low-to-high order.", "Rating Scale")
    if len(codes) != len(set(codes)):
        _issue(issues, "levels.code", "Level codes must be unique.", "Read-back and downstream mapping are ambiguous.", "Assign one stable code per level.", "Rating Scale")
    for index, level in enumerate(levels, 2):
        for field in ("code", "name", "short_description", "full_description"):
            if level.get(field) in (None, ""):
                _issue(issues, "levels.%s" % field, "Required level value is missing.", "Users cannot interpret the rating consistently.", "Complete the level value.", "Rating Scale", index)
    numeric_required = "Skills Center" in consumers or ("Performance Management" in consumers and bool(_get(data, "performance.calculated_rating", False)))
    numbers = [level.get("numeric_rating") for level in levels]
    if numeric_required:
        if any(isinstance(value, bool) or not isinstance(value, int) for value in numbers):
            _issue(issues, "levels.numeric_rating", "Whole-number numeric ratings are required.", "Performance or Skills Center cannot use the scale correctly.", "Provide one whole number per level.", "Rating Scale")
        elif numbers != sorted(numbers) or len(numbers) != len(set(numbers)) or not bool(_get(data, "model.highest_number_is_best", False)):
            _issue(issues, "levels.numeric_rating", "Numbers must strictly increase and highest number must be best.", "Scale direction or calculation is invalid.", "Order low to high and confirm highest is best.", "Rating Scale")
    if "Skills Center" in consumers and any(isinstance(value, int) and not 1 <= value <= 9 for value in numbers):
        _issue(issues, "levels.numeric_rating", "Skills Center numeric values must be from 1 through 9.", "The skill-level identifier range is unsupported.", "Use strictly increasing integers within 1 through 9.", "Rating Scale")
    calculated = "Performance Management" in consumers and bool(_get(data, "performance.calculated_rating", False))
    method = str(_get(data, "performance.calculation_method", "")).lower()
    if calculated and method in ("average", "sum", "band"):
        precision = _get(data, "performance.calculation_precision", None)
        if not isinstance(precision, int) or precision < 0:
            _issue(issues, "performance.calculation_precision", "A nonnegative integer precision is required.", "Range boundaries cannot be checked.", "Provide the downstream calculation precision.")
        if not _get(data, "performance.rounding_policy", ""):
            _issue(issues, "performance.rounding_policy", "Rounding policy is required.", "Calculated results may map to different levels.", "Document the downstream rounding policy.")
        ranges = [(level.get("range_from"), level.get("range_to")) for level in levels]
        if any(level.get("review_point") is None or start is None or end is None for level, (start, end) in zip(levels, ranges)):
            _issue(issues, "levels.review_point/range", "Every level needs review point, range start, and range end.", "Calculated ratings cannot map completely.", "Complete all review points and ranges.", "Review Points and Ranges")
        else:
            step = 10 ** (-precision) if isinstance(precision, int) and precision >= 0 else 0
            for index, (start, end) in enumerate(ranges):
                if start > end:
                    _issue(issues, "levels.range", "Range start exceeds range end.", "The level can never be selected.", "Correct the boundaries.", "Review Points and Ranges", index + 2)
                if index and abs(start - ranges[index - 1][1] - step) > 1e-9:
                    _issue(issues, "levels.range", "Ranges overlap or have an unexplained precision gap.", "Some calculated values map twice or not at all.", "Make adjacent ranges contiguous at declared precision.", "Review Points and Ranges", index + 2)
    categories_required = "Talent Review and Succession" in consumers and bool(_get(data, "talent_review.categories_required", False))
    if categories_required and any(not level.get("category") for level in levels):
        _issue(issues, "levels.category", "Every level requires a Talent Review category.", "Analytics or box-chart grouping is incomplete.", "Assign a category to every level.", "Rating Categories")
    direct = "Compensation" in consumers and bool(_get(data, "compensation.direct_distributions_required", False))
    if direct:
        for index, level in enumerate(levels, 2):
            low, high = level.get("distribution_min"), level.get("distribution_max")
            if low is None or high is None or not 0 <= low <= 100 or not 0 <= high <= 100 or low > high:
                _issue(issues, "levels.distribution", "Compensation minimum/maximum is missing, outside 0..100, or reversed.", "The direct distribution is invalid.", "Provide 0..100 values with minimum not greater than maximum.", "Rating Distributions", index)
        threshold = _get(data, "compensation.distribution_threshold", None)
        if not isinstance(threshold, (int, float)) or isinstance(threshold, bool) or not 0 <= threshold <= 100:
            _issue(issues, "compensation.distribution_threshold", "Distribution threshold must be from 0 through 100.", "Compensation validation cannot be applied.", "Provide a valid percentage.", "Rating Distributions")
    target = _get(data, "performance.target_distribution", []) or []
    if target and abs(sum(float(item.get("percentage", 0)) for item in target) - 100.0) > 1e-9:
        _issue(issues, "performance.target_distribution", "Target percentages must total 100.", "The downstream Performance distribution is invalid.", "Correct the downstream handoff percentages.", "Rating Distributions")
    if consumers == ["Skills Center"] or set(consumers) == set(["Skills Center"]):
        extras = any(level.get(field) is not None and level.get(field) != "" for level in levels for field in ("review_point", "range_from", "range_to", "category", "distribution_min", "distribution_max"))
        if extras:
            _issue(issues, "levels", "Skills-Center-only requests cannot add optional components.", "The model exceeds its consumer scope.", "Remove review, range, category, and distribution values or select the requiring consumer.", "Rating Scale")
    languages = _get(data, "model.languages", []) or []
    translations = data.get("translations", [])
    for language in languages[1:]:
        header = [item for item in translations if item.get("language") == language and item.get("entity_type") == "model"]
        translated_codes = set(item.get("entity_code") for item in translations if item.get("language") == language and item.get("entity_type") == "level")
        if not header or any(code not in translated_codes for code in codes):
            _issue(issues, "translations", "Header and every level need a translation for %s." % language, "Users receive mixed-language labels.", "Add the model and all level translations.", "Translations")
    handoff_consumers = set(item.get("consumer") for item in data.get("handoffs", []))
    for consumer in consumers:
        if consumer not in handoff_consumers:
            _issue(issues, "handoffs", "Missing handoff for %s." % consumer, "Downstream ownership and tests are unclear.", "Add a complete consumer handoff.", "Consumer Handoffs")
    return {"schema_version": "1.0", "status": "valid" if not issues else "blocked", "issue_count": len(issues), "issues": issues}


def inspect_mapping(path):
    sheets = read_xlsx(path)
    expected = {"Model Requirements": ["Field", "Value"], "Rating Scale": list(LEVEL_FIELDS),
                "Translations": ["language", "entity_type", "entity_code", "name", "short_description", "full_description"],
                "Consumer Handoffs": list(HANDOFF_FIELDS)}
    reviews = []
    for expected_sheet, headers in expected.items():
        candidates = difflib.get_close_matches(expected_sheet, list(sheets.keys()), n=3, cutoff=0.45)
        actual = expected_sheet if expected_sheet in sheets else (candidates[0] if len(candidates) == 1 else None)
        actual_headers = sheets.get(actual, [[]])[0] if actual and sheets.get(actual) else []
        exact = actual == expected_sheet and actual_headers == headers
        reviews.append({"expected_sheet": expected_sheet, "candidate_sheet": actual,
                        "expected_headers": headers, "candidate_headers": actual_headers,
                        "status": "exact" if exact else "review_required"})
    return {"status": "ready" if all(item["status"] == "exact" for item in reviews) else "review_required",
            "automatic_mapping_applied": False, "mappings": reviews}


def load_input(path):
    if path.lower().endswith(".xlsx"):
        return workbook_to_data(path)
    with open(path, "r", encoding="utf-8") as stream:
        return json.load(stream)


def write_json(path, value):
    parent = os.path.dirname(os.path.abspath(path))
    if parent and not os.path.isdir(parent):
        os.makedirs(parent)
    with open(path, "w", encoding="utf-8") as stream:
        json.dump(value, stream, indent=2, sort_keys=True)
        stream.write("\n")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command")
    generate = subparsers.add_parser("generate", help="Generate the tailored requirements workbook.")
    generate.add_argument("--input", required=True)
    generate.add_argument("--output", required=True)
    template = subparsers.add_parser(
        "generate-template", help="Generate a fillable guidance workbook without complete requirements."
    )
    template.add_argument("--output", required=True)
    template.add_argument("--consumer", action="append", choices=CONSUMERS, default=[])
    template.add_argument("--level-count", type=int, default=5)
    check = subparsers.add_parser("validate", help="Validate normalized JSON or a generated workbook.")
    check.add_argument("--input", required=True)
    check.add_argument("--output", required=True)
    check.add_argument("--normalized-output")
    inspect = subparsers.add_parser("inspect-mapping", help="Review customer workbook mapping without applying it.")
    inspect.add_argument("--input", required=True)
    inspect.add_argument("--output", required=True)
    args = parser.parse_args(argv)
    if args.command == "generate":
        data = load_input(args.input)
        result = validate(data)
        if result["status"] != "valid":
            sys.stderr.write(json.dumps(result, indent=2) + "\n")
            return 2
        write_xlsx(args.output, workbook_sheets(data))
        return 0
    if args.command == "generate-template":
        try:
            sheets = template_workbook_sheets(
                args.consumer,
                args.level_count,
                source_name=os.path.basename(args.output),
            )
        except ValueError as error:
            sys.stderr.write(str(error) + "\n")
            return 2
        write_xlsx(args.output, sheets)
        return 0
    if args.command == "validate":
        data = load_input(args.input)
        result = validate(data)
        write_json(args.output, result)
        if args.normalized_output:
            write_json(args.normalized_output, data)
        return 0 if result["status"] == "valid" else 2
    if args.command == "inspect-mapping":
        write_json(args.output, inspect_mapping(args.input))
        return 0
    parser.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())
